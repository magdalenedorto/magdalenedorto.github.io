-- Run this once in the Supabase SQL Editor for the portfolio_reviews table.
-- Existing rows are treated as private unless their old privacy value explicitly said public.
-- This resets policies on this table so older broad anonymous policies cannot expose private feedback.

begin;

create table if not exists public.portfolio_reviews (
    id bigint generated by default as identity primary key,
    visitor_name text not null default 'Anonymous',
    visitor_location text not null default 'Not shared',
    star_rating integer not null default 5,
    public_comment text not null,
    privacy text not null default 'private',
    created_at timestamptz not null default now()
);

alter table public.portfolio_reviews
    add column if not exists visitor_name text,
    add column if not exists visitor_location text,
    add column if not exists star_rating integer,
    add column if not exists public_comment text,
    add column if not exists created_at timestamptz;

alter table public.portfolio_reviews
    add column if not exists privacy text;

update public.portfolio_reviews
set visitor_name = coalesce(nullif(trim(visitor_name), ''), 'Anonymous'),
    visitor_location = coalesce(nullif(trim(visitor_location), ''), 'Not shared'),
    star_rating = greatest(1, least(5, coalesce(star_rating, 5))),
    public_comment = coalesce(public_comment, ''),
    created_at = coalesce(created_at, now());

update public.portfolio_reviews
set privacy = case
    when lower(trim(coalesce(privacy, ''))) like 'public%' then 'public'
    else 'private'
end;

alter table public.portfolio_reviews
    alter column visitor_name set default 'Anonymous',
    alter column visitor_name set not null,
    alter column visitor_location set default 'Not shared',
    alter column visitor_location set not null,
    alter column star_rating set default 5,
    alter column star_rating set not null,
    alter column public_comment set not null,
    alter column created_at set default now(),
    alter column created_at set not null,
    alter column privacy set default 'private',
    alter column privacy set not null;

alter table public.portfolio_reviews
    drop constraint if exists portfolio_reviews_privacy_check;

alter table public.portfolio_reviews
    add constraint portfolio_reviews_privacy_check
    check (privacy in ('private', 'public'));

alter table public.portfolio_reviews enable row level security;

do $$
declare
    existing_policy record;
begin
    for existing_policy in
        select policyname
        from pg_policies
        where schemaname = 'public' and tablename = 'portfolio_reviews'
    loop
        execute format('drop policy if exists %I on public.portfolio_reviews', existing_policy.policyname);
    end loop;
end
$$;

grant usage on schema public to anon, authenticated;
grant select, insert on table public.portfolio_reviews to anon, authenticated;

drop policy if exists portfolio_reviews_select_public on public.portfolio_reviews;
create policy portfolio_reviews_select_public
on public.portfolio_reviews
for select
to anon, authenticated
using (privacy = 'public');

drop policy if exists portfolio_reviews_insert_public on public.portfolio_reviews;
create policy portfolio_reviews_insert_public
on public.portfolio_reviews
for insert
to anon, authenticated
with check (
    privacy = 'public'
    and star_rating between 1 and 5
    and char_length(btrim(public_comment)) between 3 and 3000
);

do $$
declare
    sequence_name text;
begin
    sequence_name := pg_get_serial_sequence('public.portfolio_reviews', 'id');
    if sequence_name is not null then
        execute format('grant usage, select on sequence %s to anon, authenticated', sequence_name);
    end if;
end
$$;

commit;
